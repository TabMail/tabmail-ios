    /// The oracle is OPT-IN. While no expectation has ever been registered,
    /// every mutating handler's check is a single `isEmpty` branch — this is
    /// what keeps the other ~7,700 tests behaviorally unchanged. Exercises the
    /// whole mutating surface with no registration at all.
    @Test("oracle is inert until a test registers an expectation")
    func oracleIsInertWhenNoExpectationRegistered() async throws {
        let server = FakeIMAPServer(mailboxes: [
            "INBOX": [
                Self.message(uid: 111, id: "oracle-inert-a@example.com"),
                Self.message(uid: 112, id: "oracle-inert-b@example.com"),
                Self.message(uid: 113, id: "oracle-inert-c@example.com"),
                Self.message(uid: 114, id: "oracle-inert-d@example.com"),
            ],
            "Archive": [],
        ])
        server.setFlags(["\\Deleted"], in: "INBOX", uid: 114)
        try server.start()
        defer { server.stop() }

        try await Self.withClient(server) { client in
            _ = try await client.selectMailbox("INBOX")
            try await client.store(flags: [.flagged], on: UIDSet(UID(111)), operation: .add)
            try await client.copy(messages: UIDSet(UID(111)), to: "Archive")
            try await client.move(messages: UIDSet(UID(112)), to: "Archive")
            try await client.expunge(messages: UIDSet(UID(113)))
            try await client.expunge()
