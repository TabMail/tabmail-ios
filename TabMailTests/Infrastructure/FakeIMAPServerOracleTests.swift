    // MARK: - Deliverable 2: the epoch-replacement model

    /// `resetMailboxAfterNextSuccessfulResponse` models a UIDVALIDITY change
    /// taking effect at an await boundary — immediately after a successful
    /// protocol response, without pausing either side of the socket. This test
    /// proves all three properties the later Tier-3 move-path proof depends on:
    ///
    /// 1. **Not eager.** After arming, and after an unrelated command has come
    ///    and gone, a SELECT still reports the OLD epoch.
    /// 2. **UIDVALIDITY really changes at that point.** The first SELECT after
    ///    the armed command reports the NEW epoch.
    /// 3. **The UID's referent really changes.** UID 107 denoted message A
    ///    before the reset and a different message afterwards — demonstrated
    ///    by re-issuing the IDENTICAL `UID STORE 107` and watching it land on
    ///    the decoy while the oracle reports the wrong-message hit.
    ///
    /// Property 3 IS the mid-sequence epoch hazard, reproduced end-to-end at
    /// the wire: the two STOREs are byte-identical commands, one correct and
    /// one catastrophic, and only the epoch between them differs.
    ///
    /// Inversion evidence (recorded 2026-07-30), run in both directions
    /// because the two mechanisms must be shown to be separable:
    /// - With `recordOracleCheck` neutralized, the epoch assertions (1 → 2)
    ///   and the decoy-flag assertion still hold — the epoch model is proven
    ///   independently of the oracle — while only the violation assertion
    ///   fails.
    /// - With the post-response reset application neutralized (the
    ///   `postResponseMailboxResets` block in the client loop made
    ///   unreachable), this test fails at the UIDVALIDITY assertion
    ///   (`1 == 2`), at the occupant assertion (INBOX still holds the E1
    ///   target), and at the violation assertion — while every oracle test
    ///   above stays green.
    @Test("post-response reset changes UIDVALIDITY and repoints the UID at a different message")
    func postResponseResetChangesUidValidityAndUidOccupant() async throws {
        let targetId = "oracle-epoch-target@example.com"
        let decoyId = "oracle-epoch-decoy@example.com"
        let sharedUID = 107
        let server = FakeIMAPServer(mailboxes: [
            "INBOX": [Self.message(uid: sharedUID, id: targetId)],
        ])
        server.setUidValidity(1, for: "INBOX")
        server.expectMutation(rfc822MessageId: targetId)
        // E1 → E2 lands the instant the first `UID STORE 107` is acknowledged.
        // The decoy reuses the very same UID, which is exactly what a real
        // UIDVALIDITY reset is free to do.
        server.resetMailboxAfterNextSuccessfulResponse(
            containing: "UID STORE \(sharedUID)",
            mailbox: "INBOX",
            uidValidity: 2,
            messages: [Self.message(uid: sharedUID, id: decoyId)]
        )
        try server.start()
        defer { server.stop() }

        try await Self.withClient(server) { client in
            // (1) Armed but not fired: an unrelated round-trip must not
            // trigger it.
            _ = try await client.noop()
            let beforeSelection = try await client.selectMailbox("INBOX")
            #expect(beforeSelection.uidValidity.value == 1)
            #expect(server.messageIDs(in: "INBOX") == ["<\(targetId)>"])

            // The E1 mutation: correct, and the oracle agrees.
            try await client.store(flags: [.seen], on: UIDSet(UID(sharedUID)), operation: .add)
            #expect(server.wrongMessageViolations().isEmpty)

            // (2) The epoch moved the moment that response was written.
            let afterSelection = try await client.selectMailbox("INBOX")
            #expect(afterSelection.uidValidity.value == 2)

            // (3) The same UID now denotes a different message entirely — the
            // E1 target is gone from the mailbox and the decoy holds its UID.
            #expect(server.messageIDs(in: "INBOX") == ["<\(decoyId)>"])
            #expect(server.flags(in: "INBOX", rfc822MessageId: targetId) == nil)
            // The epoch replacement carries flags too: the decoy starts clean
            // even though the pre-reset occupant of UID 107 had just been
            // marked \Seen.
            #expect(server.flags(in: "INBOX", uid: sharedUID).isEmpty)

            // The byte-identical repeat of the E1 command now mutates the decoy.
            try await client.store(flags: [.seen], on: UIDSet(UID(sharedUID)), operation: .add)
            #expect(server.flags(in: "INBOX", rfc822MessageId: decoyId)?.contains("\\Seen") == true)
        }

        let violations = server.wrongMessageViolations()
        #expect(violations.count == 1)
        guard violations.count == 1 else { return }
        #expect(violations[0].command.hasPrefix("UID STORE"))
        #expect(violations[0].uid == sharedUID)
        #expect(violations[0].actualRfc == decoyId)
        #expect(violations[0].expectedRfcs == [targetId])
    }

    /// The reset is one-shot and consumed on first match: a second occurrence
    /// of the same command does not re-apply it. A test that armed once must
    /// be able to keep driving the wire afterwards without the mailbox
    /// silently rewinding under it.
    ///
    /// Inversion evidence (recorded 2026-07-30): with the post-response reset
    /// application made unreachable, both UIDVALIDITY assertions fail
    /// (`3 == 4`); with only `recordOracleCheck` neutralized this test stays
    /// green, since it asserts nothing about the oracle.
    @Test("post-response reset is consumed by the first matching response only")
    func postResponseResetAppliesExactlyOnce() async throws {
        let targetId = "oracle-epoch-once-target@example.com"
        let decoyId = "oracle-epoch-once-decoy@example.com"
        let survivorId = "oracle-epoch-once-survivor@example.com"
        let sharedUID = 161
        let server = FakeIMAPServer(mailboxes: [
            "INBOX": [Self.message(uid: sharedUID, id: targetId)],
        ])
        server.setUidValidity(3, for: "INBOX")
        server.resetMailboxAfterNextSuccessfulResponse(
            containing: "UID STORE \(sharedUID)",
            mailbox: "INBOX",
            uidValidity: 4,
            messages: [Self.message(uid: sharedUID, id: decoyId)]
        )
        try server.start()
        defer { server.stop() }

        try await Self.withClient(server) { client in
            _ = try await client.selectMailbox("INBOX")
            try await client.store(flags: [.seen], on: UIDSet(UID(sharedUID)), operation: .add)
            let afterFirstStore = try await client.selectMailbox("INBOX")
            #expect(afterFirstStore.uidValidity.value == 4)

            // A message arriving after the reset must survive the second STORE.
            server.setMessages(
                [Self.message(uid: sharedUID, id: decoyId), Self.message(uid: 162, id: survivorId)],
                in: "INBOX"
            )
            try await client.store(flags: [.flagged], on: UIDSet(UID(sharedUID)), operation: .add)

            let afterSecondStore = try await client.selectMailbox("INBOX")
            #expect(afterSecondStore.uidValidity.value == 4)
        }

        #expect(Set(server.messageIDs(in: "INBOX")) == ["<\(decoyId)>", "<\(survivorId)>"])
    }

