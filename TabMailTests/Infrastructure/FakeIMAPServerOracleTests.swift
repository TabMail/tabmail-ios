/// T0.2 — the red-first proof for the two `FakeIMAPServer` mechanisms the v3
/// safety work is built on. Both mechanisms landed with T0.1 (they are woven
/// through the fake's state and every mutating handler, so they could not be
/// excluded); what did NOT land is the evidence that they actually work.
///
/// **Deliverable 1 — the wrong-message wire oracle.** Every mutating IMAP
/// command (`UID STORE`, `UID MOVE`, `UID COPY`, `UID EXPUNGE`, plain
/// `EXPUNGE`) resolves its target UID to the mailbox's CURRENT occupant
/// in-lock, pre-mutation, and records a `WrongMessageViolation` when that
/// occupant's Message-ID is not one the test declared it was mutating. This is
/// the primary instrument for C3-I1…C3-I6 (`PLAN_IOS_REFACTOR_V3.md` §3.2):
/// every later Tier-2/Tier-3 test asserts `wrongMessageViolations().isEmpty`,
/// and an assertion that can never fail proves nothing. These tests are the
/// positive control for that assertion.
///
/// **Deliverable 2 — the epoch-replacement model.**
/// `resetMailboxAfterNextSuccessfulResponse` applies a complete mailbox epoch
/// replacement (UIDVALIDITY + message list + flags) immediately after the
/// matching command's successful response is written to the client. That is
/// what makes the mid-sequence epoch hazard reproducible at all: a UID
/// resolved under epoch E1 and mutated after the mailbox has moved to E2
/// lands on a different message. A later Tier-3 item uses exactly this to
/// prove the IMAP move path cannot mutate the wrong message.
///
/// **Why these drive the wire directly instead of a provider API.** These are
/// harness tests: they pin the FAKE's contract, so they must stay true no
/// matter how production changes. A test that produced the mis-target by
/// exploiting a production defect would go green the moment that defect is
/// fixed — an oracle proof that self-destructs. Here the mis-target comes from
/// the TEST's own declaration (it registers B and mutates A's UID), which no
/// production change can ever make correct. One test
/// (`oracleObservesProductionIMAPProviderStore`) closes the loop by proving
/// the oracle also sees traffic generated by the real `IMAPProvider`.
///
/// `.serialized` — the fake binds a listening socket; parallel tests would
/// contend on ephemeral port allocation.
@Suite("FakeIMAPServer wrong-message oracle + epoch-replacement model", .serialized)
struct FakeIMAPServerOracleTests {

    // MARK: - Fixtures

    private static func rfc822(messageId: String, subject: String = "oracle-fixture") -> String {
        """
        From: Test Sender <sender@example.com>\r
        To: Recipient <recipient@example.com>\r
        Subject: \(subject)\r
        Date: Thu, 01 Jan 2026 00:00:00 +0000\r
        Message-ID: <\(messageId)>\r
        Content-Type: text/plain; charset=utf-8\r
        \r
        oracle fixture body.\r

        """
    }

    private static func message(uid: Int, id: String) -> FakeIMAPServer.Message {
        FakeIMAPServer.makeMessage(uid: uid, rfc822Text: rfc822(messageId: id))
    }

    /// Runs `body` against a freshly logged-in raw SwiftMail client and logs
    /// out before returning. Driving the wire directly is deliberate — see the
    /// suite doc comment. The logout is awaited rather than deferred into a
    /// detached `Task`, so it can never race the fake's socket teardown.
    private static func withClient<T>(
        _ server: FakeIMAPServer,
        _ body: (SwiftMail.IMAPServer) async throws -> T
    ) async throws -> T {
        let client = SwiftMail.IMAPServer(host: "127.0.0.1", port: server.port, useTLS: false)
        try await client.connect()
        try await client.login(username: server.username, password: server.password)
        do {
            let result = try await body(client)
            try? await client.logout()
            return result
        } catch {
            try? await client.logout()
            throw error
        }
    }

    // MARK: - Deliverable 1: the oracle fires

    /// THE headline red-first proof for T0.2: a `UID STORE` aimed at a UID
    /// whose current occupant is not the message the test declared it was
    /// mutating raises exactly one `WrongMessageViolation`, naming the
    /// command, the mailbox, the UID, and the Message-ID that was actually
    /// hit.
    ///
    /// Inversion evidence (recorded 2026-07-30): with `recordOracleCheck`'s
    /// body neutralized to an immediate `return`, this test fails at the
    /// `violations.count == 1` expectation — it goes green-when-it-should-be-
    /// red. It passes only because the oracle exists.
    @Test("oracle fires on a UID STORE aimed at a UID the test never declared")
    func oracleFiresOnMisTargetedUIDStore() async throws {
        let occupantId = "oracle-store-occupant@example.com"
        let declaredId = "oracle-store-declared@example.com"
        let occupantUID = 101
        let declaredUID = 102
        let server = FakeIMAPServer(mailboxes: [
            "INBOX": [
                Self.message(uid: occupantUID, id: occupantId),
                Self.message(uid: declaredUID, id: declaredId),
            ],
        ])
        // The test declares it is mutating `declaredId` — and then deliberately
        // mis-targets UID 101, whose current occupant is `occupantId`.
        server.expectMutation(rfc822MessageId: declaredId)
        try server.start()
        defer { server.stop() }

        try await Self.withClient(server) { client in
            _ = try await client.selectMailbox("INBOX")
            try await client.store(flags: [.seen], on: UIDSet(UID(occupantUID)), operation: .add)
        }

        let violations = server.wrongMessageViolations()
        #expect(violations.count == 1)
        guard violations.count == 1 else { return }
        #expect(violations[0].command.hasPrefix("UID STORE"))
        #expect(violations[0].mailbox == "INBOX")
        #expect(violations[0].uid == occupantUID)
        #expect(violations[0].actualRfc == occupantId)
        #expect(violations[0].expectedRfcs == [declaredId])
        // The oracle OBSERVES; it never blocks. The wrong-message mutation
        // really did land — which is precisely the class of defect it exists
        // to make visible.
        #expect(server.flags(in: "INBOX", uid: occupantUID).contains("\\Seen"))
    }

