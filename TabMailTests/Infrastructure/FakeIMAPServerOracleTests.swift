        // Every mutating command ran, and the oracle recorded nothing.
        let commands = server.recordedCommands()
        #expect(commands.contains { $0.hasPrefix("UID STORE") })
        #expect(commands.contains { $0.hasPrefix("UID COPY") })
        #expect(commands.contains { $0.hasPrefix("UID MOVE") })
        #expect(commands.contains { $0.hasPrefix("UID EXPUNGE") })
        #expect(commands.contains("EXPUNGE"))
        #expect(server.wrongMessageViolations().isEmpty)
    }

